import { createServer } from 'node:http';
/** Explicit deterministic transport fixture. Never imported by application code. */
export async function startAIProviderFixture(port = 0) {
  const requests = [];
  const server = createServer(async (req, res) => {
    if (req.method !== 'POST' || req.url !== '/v1/chat/completions') {
      res.writeHead(404).end();
      return;
    }
    try {
      let raw = '';
      for await (const chunk of req) {
        raw += chunk;
        if (Buffer.byteLength(raw) > 200000) throw new Error('Fixture input too large');
      }
      const body = JSON.parse(raw),
        input = JSON.parse(body.messages.at(-1).content),
        tasks = input.authorizedContext.tasks;
      requests.push({
        model: body.model,
        mode: input.mode,
        structured: body.response_format?.type,
        taskIds: tasks.map((row) => row.id),
      });
      const first = tasks.find((row) => row.id === input.selectedTaskId) ?? tasks[0];
      const output = {
        answer: `Component demonstration: deterministic test-provider ${input.mode} draft. ${tasks.length} authorized work items in the test snapshot. Verify suggestions before use.`,
        references: first ? [first.id] : [],
        tasks: [],
        priorities: [],
        matches: [],
      };
      if (['tasks', 'subtasks'].includes(input.mode))
        output.tasks = [
          {
            title:
              input.mode === 'subtasks'
                ? 'Review acceptance criteria'
                : 'Prepare the launch checklist',
            description:
              'Component demonstration generated by the deterministic test provider. Review scope and evidence.',
            priority: 'normal',
          },
          {
            title: 'Verify the finished work',
            description: 'Run checks and record their actual results.',
            priority: 'high',
          },
        ];
      if (input.mode === 'priorities')
        output.priorities = tasks
          .filter((row) => row.status !== 'done')
          .slice(0, 2)
          .map((row) => ({
            taskId: row.id,
            priority: 'high',
            reason: 'Test-provider suggestion for review; current work remains unfinished.',
          }));
      if (input.mode === 'search') output.matches = tasks.slice(0, 3).map((row) => row.id);
      res.writeHead(200, { 'Content-Type': 'application/json' }).end(
        JSON.stringify({
          id: 'orbit-test-completion',
          object: 'chat.completion',
          created: Math.floor(Date.now() / 1000),
          model: 'orbit-test-fixture',
          choices: [
            {
              index: 0,
              message: { role: 'assistant', content: JSON.stringify(output) },
              finish_reason: 'stop',
            },
          ],
          usage: { prompt_tokens: 100, completion_tokens: 80, total_tokens: 180 },
        }),
      );
    } catch {
      res
        .writeHead(400, { 'Content-Type': 'application/json' })
        .end(JSON.stringify({ error: { message: 'Invalid deterministic fixture request' } }));
    }
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', resolve);
  });
  return {
    url: `http://127.0.0.1:${server.address().port}/v1`,
    requests,
    close: () =>
      new Promise((resolve, reject) =>
        server.close((error) => (error ? reject(error) : resolve())),
      ),
  };
}
